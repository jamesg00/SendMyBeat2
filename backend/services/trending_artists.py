# What producers and buyers actually type, where the display name has punctuation or is long.
SEARCH_NAME_OVERRIDES: dict[str, str] = {
    "a-boogie": "a boogie",
    "ski-mask": "ski mask",
    "the-notorious-big": "biggie",
}


def search_name(slug: str, name: str) -> str:
    """The artist as typed in a search: lowercase, "$" as "s", no dots, "!" or apostrophes,
    hyphens as spaces. "A$AP Rocky" -> "asap rocky", "J. Cole" -> "j cole", "Jay-Z" -> "jay z"."""
    if slug in SEARCH_NAME_OVERRIDES:
        return SEARCH_NAME_OVERRIDES[slug]
    text = name.lower().replace("$", "s").replace("-", " ")
    text = re.sub(r"[.!']", "", text)
    return re.sub(r"\s+", " ", text).strip()


def type_beat_query(slug: str, name: str) -> str:
    return f"{search_name(slug, name)} type beat"
